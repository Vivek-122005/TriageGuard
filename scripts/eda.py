"""Exploratory analysis of the synthetic corpus (M2).

Writes docs/eda.md (readable report) and reports/eda_stats.json (raw numbers).
Standard library only, so it runs anywhere the generator runs.

Usage: python3 scripts/eda.py [--corpus data/corpus]
"""

import argparse
import json
import re
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from triageguard.schema import DOC_TYPES, FIELDS_BY_TYPE, PII_LABELS, ROUTES, SPLITS  # noqa: E402

TOKEN = re.compile(r"[A-Za-z]+")


def load(corpus: Path) -> dict:
    return {s: [json.loads(l) for l in open(corpus / f"{s}.jsonl")] for s in SPLITS}


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "-"


def quantiles(xs):
    xs = sorted(xs)
    q = lambda p: xs[min(len(xs) - 1, int(p * len(xs)))]
    return {"min": xs[0], "median": q(0.5), "p95": q(0.95), "max": xs[-1], "mean": round(statistics.mean(xs), 1)}


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main(corpus: Path):
    data = load(corpus)
    alld = [d for s in SPLITS for d in data[s]]
    stats = {}
    md = ["# M2 exploratory data analysis",
          "",
          f"Generated by `scripts/eda.py` from `{corpus.relative_to(ROOT) if corpus.is_absolute() else corpus}`. "
          "Every number below is recomputed from the corpus files; rerun the script after regenerating.",
          ""]

    # 1. Size and splits
    md += ["## 1. Size and splits", ""]
    rows = []
    for s in SPLITS:
        docs = data[s]
        rows.append([s, len(docs), len({d['patient_id'] for d in docs}), len({d['episode_id'] for d in docs}),
                     pct(sum(d['noise'] != 'clean' for d in docs), len(docs)), pct(sum(d['ocr'] for d in docs), len(docs)),
                     pct(sum(d['held_out_layout'] for d in docs), len(docs))])
    rows.append(["**all**", len(alld), len({d['patient_id'] for d in alld}), len({d['episode_id'] for d in alld}),
                 pct(sum(d['noise'] != 'clean' for d in alld), len(alld)), pct(sum(d['ocr'] for d in alld), len(alld)),
                 pct(sum(d['held_out_layout'] for d in alld), len(alld))])
    md += [table(["split", "documents", "patients", "episodes", "noisy", "OCR-style", "held-out layout"], rows), ""]
    stats["split_sizes"] = {s: len(data[s]) for s in SPLITS}

    # 2. Document types
    md += ["## 2. Document types", ""]
    rows = []
    for t in DOC_TYPES:
        rows.append([t] + [sum(d["doc_type"] == t for d in data[s]) for s in SPLITS] + [pct(sum(d["doc_type"] == t for d in alld), len(alld))])
    md += [table(["type"] + SPLITS + ["share"], rows), "",
           "Claim forms and bills are the largest classes because every episode produces both; "
           "pre-authorization letters are the smallest. Macro-F1 (the M1 target metric) weights them equally.", ""]
    stats["type_counts"] = dict(Counter(d["doc_type"] for d in alld))

    # 3. Routes
    md += ["## 3. Routes", ""]
    rows = []
    for s in SPLITS:
        c = Counter(d["route"] for d in data[s])
        rows.append([s] + [f"{c[r]} ({pct(c[r], len(data[s]))})" for r in ROUTES])
    md += [table(["split"] + ROUTES, rows), ""]
    rows = []
    for t in DOC_TYPES:
        docs = [d for d in alld if d["doc_type"] == t]
        c = Counter(d["route"] for d in docs)
        rows.append([t] + [pct(c[r], len(docs)) for r in ROUTES])
    md += ["Route mix by document type (all splits):", "", table(["type"] + ROUTES, rows), ""]
    sig = Counter(s for d in alld for s in d["route_signals"])
    multi = sum(len(d["route_signals"]) > 1 for d in alld)
    hidden = sum(1 for d in alld if d["injected_signals"] and d["route"] != "suspicious")
    hv_and_susp = sum(1 for d in alld if d["route"] == "suspicious" and d["amount_high_value"])
    md += [table(["signal", "documents showing it"], [[k, v] for k, v in sig.most_common()]), "",
           f"- {multi} documents show more than one warning sign.",
           f"- {hv_and_susp} suspicious documents would also have been high-value; suspicious wins by design.",
           f"- {hidden} documents come from an episode with an injected sign that the document itself does not reveal "
           "(for example a lab report from an episode with a duplicated bill line). They are labelled by what they show, "
           "so they are routine or high-value. This is intended: a label must be recoverable from the text.", ""]
    stats["routes"] = {s: dict(Counter(d["route"] for d in data[s])) for s in SPLITS}
    stats["signals"] = dict(sig)

    # 4. Amounts and the ambiguous band
    amts = [d["fields"].get("claimed_amount") or d["fields"].get("total_billed") or d["fields"].get("estimated_cost") for d in alld]
    amts = [a for a in amts if a]
    band = [d for d in alld if (a := (d["fields"].get("claimed_amount") or d["fields"].get("total_billed") or d["fields"].get("estimated_cost"))) and 20000 <= a < 25000]
    band_hv = sum(d["route"] == "high_value" for d in band)
    q = quantiles(amts)
    md += ["## 4. Amounts", "",
           f"Documents with an amount field: {len(amts)}. Median ${q['median']:,.0f}, 95th percentile ${q['p95']:,.0f}, max ${q['max']:,.0f}.", "",
           f"{len(band)} documents fall in the ambiguous $20,000-$25,000 band. Of these, {band_hv} ({pct(band_hv, len(band))}) are high-value "
           "because they also show a stay of 5+ days or several procedures; the rest are not. A single amount threshold therefore "
           "cannot reproduce the labels, which is the multi-signal design M1 section 4.5 asked for.", ""]
    stats["amounts"] = q
    stats["ambiguous_band"] = {"n": len(band), "high_value": band_hv}

    # 5. Text length
    md += ["## 5. Text length (whitespace tokens)", ""]
    rows = []
    for t in DOC_TYPES:
        q = quantiles([len(d["text"].split()) for d in alld if d["doc_type"] == t])
        rows.append([t, q["min"], q["median"], q["mean"], q["p95"], q["max"]])
    md += [table(["type", "min", "median", "mean", "p95", "max"], rows), "",
           "Every document fits comfortably inside a 512-token transformer window, so M3 does not need chunking.", ""]

    # 6. PII
    md += ["## 6. PII spans", ""]
    lab = Counter(sp["label"] for d in alld for sp in d["pii"])
    per_doc = quantiles([len(d["pii"]) for d in alld])
    pii_chars = sum(sp["end"] - sp["start"] for d in alld for sp in d["pii"])
    all_chars = sum(len(d["text"]) for d in alld)
    md += [table(["label", "spans", "share"], [[l, lab[l], pct(lab[l], sum(lab.values()))] for l in PII_LABELS]), "",
           f"- {sum(lab.values())} PII spans in total, {per_doc['median']} per document (median), max {per_doc['max']}.",
           f"- PII covers {pct(pii_chars, all_chars)} of all characters, so a token classifier sees mostly negative tokens; "
           "M3 should report entity-level recall per label, not token accuracy.",
           f"- Rare labels (ACCOUNT_NUMBER, EMAIL) are where recall will be weakest; the rule baseline covers them with patterns.", ""]
    stats["pii_labels"] = dict(lab)
    surfaces = defaultdict(set)
    for d in alld:
        for sp in d["pii"]:
            if not d["ocr"]:
                surfaces[sp["label"]].add(re.sub(r"[A-Za-z]", "a", re.sub(r"\d", "9", sp["text"]))[:20])
    md += ["Surface-format variety (distinct digit/letter shapes per label, non-OCR docs):", "",
           table(["label", "distinct shapes"], [[l, len(surfaces[l])] for l in PII_LABELS]), ""]

    # 7. Fields
    md += ["## 7. Fields", ""]
    rows = []
    for t in DOC_TYPES:
        docs = [d for d in alld if d["doc_type"] == t]
        for f in FIELDS_BY_TYPE[t]:
            vals = [d["fields"][f] for d in docs]
            missing = sum(v in (None, [], "") for v in vals)
            spans = sum(any(sp["field"] == f for sp in d["field_spans"]) for d in docs)
            rows.append([t, f, pct(missing, len(docs)), pct(spans, len(docs))])
    md += [table(["type", "field", "missing", "has a text span"], rows), "",
           "Line items, tests and medicines are lists; their spans carry an `item` index and a `part` (for example "
           "`description` / `amount`), which is the tagging scheme M3's field tagger will train on.", ""]

    # 8. Vocabulary shift
    def vocab(docs):
        return Counter(w.lower() for d in docs for w in TOKEN.findall(d["text"]))
    vtrain = vocab(data["train"])
    md += ["## 8. Vocabulary shift against train", ""]
    rows = []
    for s in ["val", "test_golden", "test_hard"]:
        v = vocab(data[s])
        oov = sum(c for w, c in v.items() if w not in vtrain)
        rows.append([s, len(v), pct(oov, sum(v.values()))])
    md += [table(["split", "word types", "OOV tokens"], rows), "",
           "The golden set looks like training (low OOV). The hard set's OOV rate comes from the held-out layouts, heavy "
           "noise and OCR-style corruption: this is the gap M1 section 7.3 asks us to report openly.", ""]

    # 9. Leakage checks
    patient_splits = defaultdict(set)
    for d in alld:
        patient_splits[d["patient_id"]].add(d["split"])
    overlap = sum(len(v) > 1 for v in patient_splits.values())
    text_split = defaultdict(set)
    for d in alld:
        text_split[d["text"]].add(d["split"])
    dup_cross = sum(len(v) > 1 for v in text_split.values())
    held_leak = sum(d["held_out_layout"] and d["split"] != "test_hard" for d in alld)
    md += ["## 9. Leakage checks", "",
           table(["check", "result"], [
               ["patients in more than one split", overlap],
               ["identical texts across splits", dup_cross],
               ["held-out layout outside test_hard", held_leak],
               ["OCR-style docs outside test_hard", sum(d["ocr"] and d["split"] != "test_hard" for d in alld)],
           ]), "",
           "All four must be 0; `triageguard/data/validate.py` fails generation otherwise.", ""]
    stats["leakage"] = {"patient_overlap": overlap, "cross_split_duplicate_texts": dup_cross, "held_out_leak": held_leak}

    (ROOT / "docs" / "eda.md").write_text("\n".join(md))
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "eda_stats.json").write_text(json.dumps(stats, indent=2, default=str) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default=str(ROOT / "data" / "corpus"))
    main(Path(ap.parse_args().corpus))
